import {
  PLACEMENTS,
  normalizePromotion,
  verifyPromotionPreview
} from '../utils/promotion.js';
import * as PromotionService from '../services/promotionService.js';

const CACHE_CONTROL = 'public, max-age=30, s-maxage=120, stale-while-revalidate=300';

/**
 * GET /api/promotions/active?placement=home_hero&campaign=samsung-week
 * Published promotions currently inside their schedule, highest priority first.
 */
export const active = async (req, res) => {
  const { placement, campaign } = req.query;
  if (placement !== undefined && (typeof placement !== 'string' || !PLACEMENTS.includes(placement))) {
    return res.status(400).json({
      success: false,
      message: 'Unknown promotion placement',
      errors: [{ path: 'placement', message: 'Unknown promotion placement' }]
    });
  }
  try {
    const rows = await PromotionService.findActive({
      placement,
      campaignSlug: typeof campaign === 'string' && campaign ? campaign : undefined
    });
    res.set('Cache-Control', CACHE_CONTROL);
    return res.json({ success: true, data: rows.map(normalizePromotion) });
  } catch (error) {
    console.error(JSON.stringify({ event: 'promotion_api_error', route: 'active', message: error.message }));
    return res.status(500).json({ success: false, message: 'Failed to fetch promotions' });
  }
};

/** GET /api/promotions/:slug — one active, published promotion (e.g. campaign landing page). */
export const findBySlug = async (req, res) => {
  try {
    const row = await PromotionService.findActiveBySlug(req.params.slug);
    if (!row) return res.status(404).json({ success: false, message: 'Promotion not found' });
    res.set('Cache-Control', CACHE_CONTROL);
    return res.json({ success: true, data: normalizePromotion(row) });
  } catch (error) {
    console.error(JSON.stringify({ event: 'promotion_api_error', route: 'slug', message: error.message }));
    return res.status(500).json({ success: false, message: 'Failed to fetch promotion' });
  }
};

/**
 * GET /api/promotions/preview/:id?status=draft&expires=<ms>&signature=<hex>
 * Short-lived signed preview (generated by POST /api/admin/promotions/:id/preview-link).
 * Draft previews ignore status/schedule; "published" previews require a published record.
 */
export const preview = async (req, res) => {
  const id = String(req.params.id || '');
  const status = req.query.status === 'published' ? 'published' : 'draft';
  const expires = Number(req.query.expires);
  const signature = typeof req.query.signature === 'string' ? req.query.signature : '';

  if (!verifyPromotionPreview(id, status, expires, signature)) {
    console.warn(JSON.stringify({ event: 'promotion_preview_rejected', id }));
    return res.status(401).json({ success: false, message: 'Invalid or expired promotion preview' });
  }
  const row = await PromotionService.findById(id);
  if (!row || (status === 'published' && row.status !== 'published')) {
    return res.status(404).json({ success: false, message: 'Promotion preview not found' });
  }
  res.set('Cache-Control', 'private, no-store');
  return res.json({ success: true, data: normalizePromotion(row) });
};
